#!/usr/bin/env python3
"""Render exact prescribed motion into actual video files for receiving.

The generated film is synthetic; it is not a filmed physical pendulum. Pillow
renders deterministic analytic coordinates. FFmpeg encodes the rendered frames.
No generative image model, network source, or Motion Lab implementation is used.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import random
import subprocess

from PIL import Image, ImageDraw

WIDTH, HEIGHT, FPS, COUNT, SCALE = 640, 480, 30, 240, 3
PIVOT, RADIUS = (320, 90), 230
AMPLITUDE, DECAY, OMEGA, INERTIA = .60, .08, 2.8, .8


def state(index):
    t = index / FPS
    e, c, s = math.exp(-DECAY*t), math.cos(OMEGA*t), math.sin(OMEGA*t)
    angle = AMPLITUDE*e*c
    rate = AMPLITUDE*e*(-DECAY*c-OMEGA*s)
    acceleration = AMPLITUDE*e*((DECAY**2-OMEGA**2)*c+2*DECAY*OMEGA*s)
    return dict(index=index, time=t, position=angle, rate=rate,
                jointTorque=INERTIA*acceleration,
                x=PIVOT[0]+RADIUS*math.sin(angle),
                y=PIVOT[1]+RADIUS*math.cos(angle))


def frame(index, variant):
    im = Image.new('RGB', (WIDTH*SCALE, HEIGHT*SCALE), (27, 35, 45))
    d = ImageDraw.Draw(im)
    def line(points, fill, width=1):
        d.line([(round(x*SCALE), round(y*SCALE)) for x, y in points], fill=fill, width=width*SCALE)
    def ellipse(box, fill, outline=None, width=1):
        d.ellipse(tuple(round(x*SCALE) for x in box), fill=fill, outline=outline, width=width*SCALE)
    # Stationary reference grid provides a nonempty, nonmoving distractor field.
    for x in range(30, WIDTH, 40):
        line([(x,50),(x,HEIGHT-25)], (39,48,59))
    for y in range(50, HEIGHT-25, 40):
        line([(30,y),(WIDTH-30,y)], (39,48,59))
    p = state(index)
    if variant != 'blank' and not (variant == 'occluded' and 60 <= index < 75):
        line([PIVOT,(p['x'],p['y'])], (148,157,169), 3)
        ellipse((PIVOT[0]-6,PIVOT[1]-6,PIVOT[0]+6,PIVOT[1]+6), (7,14,22), (213,224,235), 2)
        x,y = p['x'],p['y']
        # Translate a fixed asymmetric patch: its texture has known correspondence.
        d.rectangle(tuple(round(z*SCALE) for z in (x-10,y-10,x+10,y+10)), fill=(250,249,232))
        rng = random.Random(1138)
        for yy in range(-8,9,3):
            for xx in range(-8,9,3):
                level = rng.choice([12,57,104,190,244])
                d.rectangle(tuple(round(z*SCALE) for z in (x+xx,y+yy,x+xx+2,y+yy+2)), fill=(level,level,level))
        ellipse((x-2,y-2,x+2,y+2),(255,205,68))
    d.text((18*SCALE,15*SCALE), 'SYNTHETIC ANALYTIC MOTION / NOT PHYSICAL VIDEO', fill=(210,220,230), font_size=12*SCALE)
    d.text((18*SCALE,445*SCALE), f'{variant.upper()}  frame {index:03d} / {index/FPS:.6f} s', fill=(180,191,204), font_size=12*SCALE)
    im = im.resize((WIDTH,HEIGHT), Image.Resampling.LANCZOS)
    if variant == 'noise':
        rng = random.Random(73000+index)
        im.putdata([tuple(max(0,min(255,c+rng.randint(-7,7))) for c in px) for px in im.getdata()])
    return im


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output', type=Path, default=Path('.receipts/motion-fixtures'))
    p.add_argument('--variants', nargs='+', choices=['clean','occluded','noise','blank'], default=['clean','occluded','blank'])
    args = p.parse_args()
    args.output.mkdir(parents=True,exist_ok=True)
    files=[]
    for variant in args.variants:
        target=args.output/f'analytic-pendulum-{variant}.webm'
        command=['ffmpeg','-y','-hide_banner','-loglevel','error','-f','rawvideo','-pixel_format','rgb24',
                 '-video_size',f'{WIDTH}x{HEIGHT}','-framerate',str(FPS),'-i','pipe:0','-an',
                 '-c:v','libvpx-vp9','-lossless','1','-threads','1','-pix_fmt','yuv420p',str(target)]
        proc=subprocess.Popen(command,stdin=subprocess.PIPE)
        for index in range(COUNT):
            proc.stdin.write(frame(index,variant).tobytes())
        proc.stdin.close()
        if proc.wait():
            raise RuntimeError(f'FFmpeg encoding failed for {variant}')
        files.append(dict(name=target.name,variant=variant,sha256=hashlib.sha256(target.read_bytes()).hexdigest(),bytes=target.stat().st_size))
    truth=dict(schema='worldlaw.motion-fixture/v1',sourceKind='synthetic_analytic_video',
               title='Prescribed damped harmonic angle; not physical nonlinear pendulum dynamics',
               provenance='Generated by scripts/generate-motion-fixtures-15cc.py using Pillow and FFmpeg; no external assets.',
               dimensions=dict(width=WIDTH,height=HEIGHT),fps=FPS,frameCount=COUNT,duration=COUNT/FPS,
               model=dict(angle='0.60*exp(-0.08*time)*cos(2.8*time)',angleUnits='rad',timeUnits='s',
                          pivot=dict(x=PIVOT[0],y=PIVOT[1]),radiusPixels=RADIUS,
                          zero='downward image vertical',positive='toward image right',inertia=INERTIA,
                          inertiaUnits='kg·m²',command=0,commandUnits='N·m'),
               dropout=dict(variant='occluded',firstIndex=60,endIndexExclusive=75),
               files=files,frames=[state(i) for i in range(COUNT)])
    (args.output/'truth.json').write_text(json.dumps(truth,indent=2)+'\n')
    frame(0,'clean').save(args.output/'analytic-pendulum-frame-zero.png')
    print(json.dumps({k:v for k,v in truth.items() if k!='frames'},indent=2))


if __name__=='__main__':
    main()
