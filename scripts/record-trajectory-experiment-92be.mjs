import assert from 'node:assert/strict';
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createHash} from 'node:crypto';
import {createChallengeServer} from './trajectory-server-92be.mjs';

// Records the actual launched application. No fitted data or UI state is mocked.
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const dir = resolve(process.env.BROWSER_ARTIFACT_DIR || '.receipts/trajectory-screened-recording-92be');
await mkdir(dir, {recursive: true});
const server = createChallengeServer();
await new Promise((resolve, reject) => {server.once('error', reject); server.listen(0, '127.0.0.1', resolve);});
let browser, context;
const errors = [], moments = [], started = Date.now();
try {
  browser = await chromium.launch({headless: true, ...(process.env.BROWSER_EXECUTABLE_PATH ? {executablePath: process.env.BROWSER_EXECUTABLE_PATH} : {})});
  context = await browser.newContext({viewport: {width: 1360, height: 1000}, reducedMotion: 'reduce', recordVideo: {dir, size: {width: 1360, height: 1000}}});
  const page = await context.newPage(), video = page.video();
  page.on('pageerror', error => errors.push(error.message));
  const panel = page.locator('#experiment-panel'), p = id => panel.locator('#' + id);
  const capture = async name => {moments.push({name,elapsedSeconds:(Date.now()-started)/1000});await page.screenshot({path:resolve(dir,name+'.png')});};
  const showPanel = async () => {await page.waitForTimeout(150);await page.evaluate(() => window.scrollTo({top: document.getElementById('experiment-panel').getBoundingClientRect().top + scrollY - 24, behavior: 'instant'}));await page.waitForTimeout(150);await page.evaluate(() => window.scrollTo({top: document.getElementById('experiment-panel').getBoundingClientRect().top + scrollY - 24, behavior: 'instant'}));};
  const save = async name => {const pending=page.waitForEvent('download');await page.locator('#export-notebook').click();const path=resolve(dir,name);await(await pending).saveAs(path);return JSON.parse(await readFile(path,'utf8'));};
  await page.goto(`http://127.0.0.1:${server.address().port}/trajectory.html`);
  await page.waitForFunction(() => document.getElementById('challenge-workspace').getAttribute('aria-busy') === 'false');
  await page.locator('#example-choice').selectOption('ambiguous');
  await page.locator('#load-example').click();
  await page.waitForFunction(() => document.getElementById('source-name').textContent.includes('Small-angle ambiguity'));
  await page.waitForFunction(() => document.getElementById('challenge-workspace').getAttribute('aria-busy') === 'false');
  assert.match(await page.locator('#source-kind').innerText(), /SYNTHETIC/);
  const before = await save('before-experiment.json');
  await page.evaluate(() => window.scrollTo({top:0,behavior:'instant'}));
  await capture('01-separate-synthetic-recordings');await page.waitForTimeout(4000);
  await showPanel();await page.waitForTimeout(2000);
  await p('plan').click();await p('release-stats').waitFor({state:'visible'});
  assert.equal(await p('preview-chart').locator('[data-series]').count(),8);
  assert.equal(await p('numerical-screen').getAttribute('data-status'),'screen_passed');
  const numericalScreen={status:'screen_passed',displayedSensitivityRad:await p('screen-sensitivity').innerText(),explanation:await p('screen-detail').innerText()};
  await showPanel();await capture('02-training-only-plan');await page.waitForTimeout(5000);
  await p('acquire').click();await p('acquisition').waitFor({state:'visible'});
  assert.equal(await page.locator('#training-count').innerText(),'322');
  assert.equal(await p('preview-chart').locator('[data-series="acquired"]').count(),1);
  await showPanel();await capture('03-independent-synthetic-acquisition');await page.waitForTimeout(6000);
  await p('apply').click();await p('revision').waitFor({state:'visible'});
  assert.equal(await page.locator('#training-count').innerText(),'523');
  assert.equal(await page.locator('#challenge-count').innerText(),'161');
  const scores=await p('revision-cards').locator('.score').allTextContents();
  assert.match(scores[0],/0\.5644/);assert.match(scores[1],/0\.000442/);
  await showPanel();await capture('04-revised-law-same-evaluation');await page.waitForTimeout(7000);
  const after = await save('after-experiment.json');
  assert.deepEqual(after.bundle.challengeRuns,before.bundle.challengeRuns);
  assert.equal(after.experiment.history.length,1);
  await page.evaluate(() => window.scrollTo({top:0,behavior:'instant'}));
  await capture('05-new-prediction-retained-evaluation');await page.waitForTimeout(5000);
  await showPanel();await page.waitForTimeout(4000);
  assert.match(await p('instrument').innerText(),/independent.*synthetic/i);
  assert.match(await p('revision').locator('.footnote').innerText(),/reuses an existing evaluation recording/);
  assert.deepEqual(errors,[]);
  const browserVersion=await browser.version();
  await context.close();context=null;
  const output=resolve(dir,'worldlaw-screened-experiment-92be.webm');await video.saveAs(output);
  const receipt={schema:'worldlaw.trajectory-video-receipt/v1',browser:browserVersion,video:{path:output,sha256:createHash('sha256').update(await readFile(output)).digest('hex'),requestedWidth:1360,requestedHeight:1000},moments,observed:{numericalScreen,source:'synthetic controlled unforced pendulum',trainingSamplesBefore:322,trainingSamplesAfter:523,unchangedEvaluationSamples:161,comparisonScores:scores,experimentHistoryLength:after.experiment.history.length},errors,scope:'Actual launched UI recording using independent virtual acquisition and real fitting. The displayed before/after comparison reuses an existing evaluation recording; it is exploratory synthetic evidence, not fresh blind or hardware validation.'};
  await writeFile(resolve(dir,'receipt-video.json'),JSON.stringify(receipt,null,2)+'\n');
  console.log(JSON.stringify(receipt,null,2));
} finally {
  if(context)await context.close();
  if(browser)await browser.close();
  await new Promise(resolve=>server.close(resolve));
}
