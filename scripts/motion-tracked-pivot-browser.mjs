/** Receive the actual decoded-video → paired tracking → notebook path. No mocked frames. */
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createProductServer} from '../server.mjs';
import {deriveAngles,calibrateNotebook} from '../src/motion/measurement.mjs';

const fixtureDir=resolve(process.env.MOTION_FIXTURE_DIR||'.receipts/tracked-pivot-fixtures');
const artifactDir=resolve(process.env.BROWSER_ARTIFACT_DIR||'.receipts/tracked-pivot-browser');
await mkdir(artifactDir,{recursive:true});
const truth=JSON.parse(await readFile(resolve(fixtureDir,'truth.json'),'utf8'));
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const server=createProductServer();await new Promise((yes,no)=>{server.once('error',no);server.listen(0,'127.0.0.1',yes);});
const origin=`http://127.0.0.1:${server.address().port}`;
const checks=[],errors=[],metrics={};let browser;
const mark=name=>{checks.push(name);console.log('PASS '+name);};
try {
  browser=await chromium.launch({headless:true,chromiumSandbox:true,...(process.env.BROWSER_EXECUTABLE_PATH?{executablePath:process.env.BROWSER_EXECUTABLE_PATH}:{})});
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  page.on('pageerror',error=>errors.push(error.message));page.setDefaultTimeout(20000);
  const source=variant=>resolve(fixtureDir,`synthetic-translating-pivot-${variant}.webm`);
  const download=async(selector,name)=>{const event=page.waitForEvent('download');await page.locator(selector).click();const file=await event;
    const path=resolve(artifactDir,name);await file.saveAs(path);return {path,value:JSON.parse(await readFile(path,'utf8'))};};
  const point=async(selector,p)=>{await page.locator(selector).click();await page.locator('#coordinate-details').evaluate(el=>el.open=true);
    await page.locator('#point-x').fill(String(p.x));await page.locator('#point-y').fill(String(p.y));await page.locator('#apply-point').click();};
  const load=async variant=>{await page.locator('#video-file').setInputFiles(source(variant));
    await page.waitForFunction(name=>document.getElementById('source-name').textContent.includes(name),`synthetic-translating-pivot-${variant}`);
    await page.waitForFunction(()=>!document.getElementById('pick-pivot').disabled);
    await page.locator('#pivot-mode').selectOption('tracked');
    await point('#pick-pivot',truth.frames[0].pivot);await point('#pick-marker',truth.frames[0].point);
    await page.locator('#sample-step').fill('.1');await page.locator('#search-radius').fill('20');await page.locator('#track-until').fill('2.8');};
  const track=async()=>{await page.locator('#track-motion').click();await page.waitForFunction(()=>!document.getElementById('cancel-tracking').hidden);
    await page.waitForFunction(()=>document.getElementById('cancel-tracking').hidden,{},{timeout:120000});};
  await page.goto(origin+'/motion.html');await load('clean');await track();
  const clean=await download('#save-notebook','clean-notebook.json');
  assert.equal(clean.value.schema,'worldlaw.motion-notebook/v2');
  assert.equal(clean.value.source.sha256,createHash('sha256').update(await readFile(source('clean'))).digest('hex'));
  assert.ok(clean.value.measurements.length>=28);assert.ok(clean.value.measurements.every(row=>row.pivotMeasurement?.point&&row.point));
  const angles=deriveAngles(clean.value);assert.equal(angles.segments.length,1);
  const angularErrors=[],pivotErrors=[];
  for(const row of angles.samples) {
    assert.equal(row.timeBasis,'decoded-media-time');const expected=truth.frames[Math.round(row.time*truth.fps)];
    angularErrors.push(Math.abs(row.position-expected.angle));
    pivotErrors.push(Math.hypot(row.pivotMeasurement.point.x-expected.pivot.x,row.pivotMeasurement.point.y-expected.pivot.y));
  }
  metrics.frames=angles.samples.length;metrics.maxAngularError=Math.max(...angularErrors);metrics.maxPivotPixelError=Math.max(...pivotErrors);
  assert.ok(metrics.maxAngularError<.015,JSON.stringify(metrics));assert.ok(metrics.maxPivotPixelError<.6,JSON.stringify(metrics));
  const fixed=deriveAngles(calibrateNotebook(clean.value,{...clean.value.calibration,pivotMode:'fixed'}));
  metrics.fixedOriginMaxError=Math.max(...fixed.samples.map(row=>Math.abs(row.position-truth.frames[Math.round(row.time*truth.fps)].angle)));
  assert.ok(metrics.fixedOriginMaxError>.1);
  mark('actual decoded frames measure translated pivot and changing marker angle; fixed-origin control fails');
  const angular=await download('#export-angles','angular-evidence.json');
  assert.equal(angular.value.samples.length,angles.samples.length);
  assert.deepEqual(angular.value.source.metadata.measurements,clean.value.measurements);
  await page.locator('#studio-export-details').evaluate(el=>el.open=true);
  assert.equal(await page.locator('#confirm-physics').isDisabled(),true);assert.equal(await page.locator('#export-studio').isDisabled(),true);
  mark('angular export carries both source observations and unsupported torque export is unavailable');
  await page.screenshot({path:resolve(artifactDir,'tracked-pivot-1440.png'),fullPage:true});
  await page.locator('#notebook-file').setInputFiles(clean.path);
  await page.waitForFunction(()=>document.getElementById('source-detail').textContent.includes('disconnected'));
  assert.equal(await page.locator('#pivot-mode').inputValue(),'tracked');
  const reopened=await download('#save-notebook','reopened-notebook.json');assert.deepEqual(reopened.value,clean.value);
  await page.locator('#attach-video').click();await page.locator('#video-file').setInputFiles(source('pivot-hidden'));
  await page.locator('#motion-error').waitFor({state:'visible'});assert.match(await page.locator('#motion-error').textContent(),/SHA-256/);
  const refused=await download('#save-notebook','wrong-source-preserved.json');assert.deepEqual(refused.value,clean.value);
  await page.locator('#attach-video').click();await page.locator('#video-file').setInputFiles(source('clean'));
  await page.waitForFunction(()=>!document.getElementById('pick-pivot').disabled);
  assert.equal(await page.locator('#motion-error').isVisible(),false);
  mark('v2 reopen preserves original paired evidence; wrong video refuses and matching source reconnects');
  // Keyboard correction at the original frame uses the original observed pivot.
  await page.locator('#pick-pivot').click();await page.locator('#evidence-canvas').focus();await page.keyboard.press('Enter');
  assert.equal(await page.locator('#motion-error').isVisible(),false);
  await page.setViewportSize({width:390,height:844});
  await page.locator('#evidence-canvas').scrollIntoViewIfNeeded();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
  await page.screenshot({path:resolve(artifactDir,'tracked-pivot-390.png'),fullPage:true});
  mark('actual desktop and 390px source overlays, keyboard pivot correction and reduced-motion layout');
  await page.setViewportSize({width:1440,height:1000});await load('pivot-hidden');await track();
  assert.match(await page.locator('#motion-notice').textContent(),/pivot:/);
  const lost=await download('#save-notebook','pivot-loss-notebook.json'),last=lost.value.measurements.at(-1);
  assert.equal(last.status,'accepted');assert.notEqual(last.pivotMeasurement.status,'accepted');assert.equal(last.pivotMeasurement.point,null);
  assert.equal(deriveAngles(lost.value).samples.at(-1).position,null);
  assert.ok(Number(await page.locator('#gap-count').textContent())>=1);
  await page.locator('#seek-time').fill('1.4');await page.locator('#seek-frame').click();
  await page.waitForFunction(()=>Math.abs(parseFloat(document.getElementById('frame-time').textContent)-1.4)<.03);
  await point('#pick-pivot',truth.frames[28].pivot);await point('#pick-marker',truth.frames[28].point);await track();
  const repaired=await download('#save-notebook','pivot-reanchored-notebook.json');
  assert.equal(deriveAngles(repaired.value).segments.length,2);
  assert.equal(repaired.value.measurements.find(row=>row.time===last.time).pivotMeasurement.point,null);
  mark('pivot-only occlusion retains marker evidence, pauses tracking and remains a gap after later re-anchor');
  await load('marker-hidden');await track();const markerLost=await download('#save-notebook','marker-loss-notebook.json');
  assert.notEqual(markerLost.value.measurements.at(-1).status,'accepted');
  assert.equal(markerLost.value.measurements.at(-1).pivotMeasurement.status,'accepted');
  assert.equal(deriveAngles(markerLost.value).samples.at(-1).position,null);
  mark('marker-only loss preserves independently accepted pivot and produces no angular observation');
  const closeTimes=structuredClone(clean.value),original=closeTimes.measurements[1];
  closeTimes.measurements.splice(1,0,{...structuredClone(original),time:original.time-5e-7,status:'manual',point:{x:20,y:20},
    pivotMeasurement:{status:'manual',point:{x:25,y:25}}});
  const closePath=resolve(artifactDir,'nearby-timestamp-notebook.json');await writeFile(closePath,JSON.stringify(closeTimes));
  await page.locator('#notebook-file').setInputFiles(closePath);
  await page.waitForFunction(()=>document.getElementById('source-detail').textContent.includes('disconnected'));
  await page.locator('#attach-video').click();await page.locator('#video-file').setInputFiles(source('clean'));
  await page.waitForFunction(()=>!document.getElementById('pick-pivot').disabled);
  await page.locator('#seek-time').fill(String(original.time));await page.locator('#seek-frame').click();
  await page.waitForFunction(time=>Math.abs(parseFloat(document.getElementById('frame-time').textContent)-time)<.0001,original.time);
  await page.locator('#pick-pivot').click();
  assert.equal(Number(await page.locator('#point-x').inputValue()),original.pivotMeasurement.point.x);
  assert.equal(Number(await page.locator('#point-y').inputValue()),original.pivotMeasurement.point.y);
  mark('a nearby imported timestamp cannot lend its pivot to a different displayed source frame');
  const downgraded=resolve(artifactDir,'invalid-v1-downgrade.json');await writeFile(downgraded,JSON.stringify({...clean.value,schema:'worldlaw.motion-notebook/v1'}));
  await page.locator('#notebook-file').setInputFiles(downgraded);await page.locator('#motion-error').waitFor({state:'visible'});
  assert.match(await page.locator('#motion-error').textContent(),/v2 motion notebook/);
  const preserved=await download('#save-notebook','after-invalid-import.json');assert.deepEqual(preserved.value,closeTimes);
  assert.deepEqual(errors,[]);mark('schema downgrade refuses atomically; complete browser course has zero page exceptions');
  await writeFile(resolve(artifactDir,'receipt.json'),JSON.stringify({checks,metrics,errors,scope:'Authored synthetic encoded videos; no physical acquisition or camera-pose qualification'},null,2)+'\n');
} finally {await browser?.close();await new Promise(resolve=>server.close(resolve));}
